"""
FileGuard - Security Analysis Report Generator
Generates clean, professional security reports for download and audit.
"""

import json
from datetime import datetime
from typing import Dict, Any

def generate_text_report(result: Dict[str, Any]) -> str:
    """Generates an exportable plain text cybersecurity analysis report."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    
    status_symbol = {
        "SAFE": "[+] VERIFIED MATCH",
        "SUSPICIOUS": "[!] CRITICAL MISMATCH / SUSPICIOUS",
        "UNKNOWN": "[?] UNKNOWN / UNSUPPORTED"
    }.get(result.get("status", "UNKNOWN"), "[?] UNKNOWN")

    lines = [
        "================================================================================",
        "             FILEGUARD - SUSPICIOUS FILE TYPE DETECTION SYSTEM                  ",
        "                      DIGITAL FORENSIC VERIFICATION REPORT                      ",
        "================================================================================",
        f"Report Generated   : {now_str}",
        f"Security Status    : {result.get('status_title', 'Unknown')} ({status_symbol})",
        f"Core Finding       : {result.get('status_message', 'No message available.')}",
        "--------------------------------------------------------------------------------",
        "FILE IDENTIFICATION & METADATA:",
        f"  * File Name          : {result.get('filename', 'Unknown')}",
        f"  * File Size          : {result.get('file_size_formatted', '0 B')}",
        f"  * Declared Extension : .{result.get('declared_extension', 'none')}",
        f"  * Actual File Format : {result.get('actual_format', 'Unknown')}",
        f"  * Category           : {result.get('actual_category', 'Unknown')}",
        f"  * MIME Type          : {result.get('mime_type', 'application/octet-stream')}",
        f"  * Valid Extensions   : {', '.join('.' + e for e in result.get('valid_extensions', [])) or 'N/A'}",
        "--------------------------------------------------------------------------------",
        "BINARY SIGNATURE ANALYSIS:",
        f"  * Magic Bytes (Hex)  : {result.get('magic_hex', 'N/A')}",
        f"  * Magic Bytes (ASCII): {result.get('magic_ascii', 'N/A')}",
        "--------------------------------------------------------------------------------",
        "CRYPTOGRAPHIC FINGERPRINTS (INTEGRITY & THREAT HUNTING):",
        f"  * MD5                : {result.get('hashes', {}).get('md5', 'N/A')}",
        f"  * SHA-1              : {result.get('hashes', {}).get('sha1', 'N/A')}",
        f"  * SHA-256            : {result.get('hashes', {}).get('sha256', 'N/A')}",
        "--------------------------------------------------------------------------------",
        "RISK & ANOMALY ASSESSMENT:",
        f"  * Threat Level       : {result.get('threat_level', 'Info')}",
        f"  * Detailed Assessment: {result.get('risk_summary', 'None provided.')}",
    ]

    anomalies = result.get("anomalies", [])
    if anomalies:
        lines.append("  * Detected Anomalies :")
        for idx, a in enumerate(anomalies, 1):
            lines.append(f"      [{idx}] {a.get('type')}: {a.get('detail')} (Severity: {a.get('severity')})")
    else:
        lines.append("  * Detected Anomalies : None detected.")

    lines.extend([
        "--------------------------------------------------------------------------------",
        "OFFICIAL CYBERSECURITY NOTICE & DISCLAIMER:",
        f"  {result.get('disclaimer', 'Format verification does not guarantee absence of malware.')}",
        "================================================================================",
        "End of Report | Generated by FileGuard - Suspicious File Type Detection System"
    ])

    return "\n".join(lines)


def generate_markdown_report(result: Dict[str, Any]) -> str:
    """Generates an exportable markdown format report."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    status = result.get("status", "UNKNOWN")
    status_badge = {
        "SAFE": "🟢 SAFE - FORMAT MATCH",
        "SUSPICIOUS": "🔴 SUSPICIOUS - MISMATCH DETECTED",
        "UNKNOWN": "🟠 UNKNOWN / UNSUPPORTED FORMAT"
    }.get(status, "⚪ UNKNOWN")

    md = f"""# FileGuard Forensic Analysis Report

**Generated:** {now_str}  
**Status:** **{status_badge}**  
**Finding:** *{result.get('status_message')}*

---

## 1. File Metadata
| Property | Value |
| :--- | :--- |
| **File Name** | `{result.get('filename')}` |
| **File Size** | {result.get('file_size_formatted')} |
| **Declared Extension** | `.{result.get('declared_extension')}` |
| **Actual Format** | **{result.get('actual_format')}** |
| **Format Category** | {result.get('actual_category')} |
| **MIME Type** | `{result.get('mime_type')}` |
| **Valid Extensions** | {', '.join(f'`{e}`' for e in result.get('valid_extensions', [])) or 'None'} |

---

## 2. Low-Level Signature Analysis
- **Magic Bytes (Hex):** `{result.get('magic_hex')}`
- **Magic Bytes (ASCII):** `{result.get('magic_ascii')}`

---

## 3. Cryptographic Hashes
- **MD5:** `{result.get('hashes', {}).get('md5')}`
- **SHA-1:** `{result.get('hashes', {}).get('sha1')}`
- **SHA-256:** `{result.get('hashes', {}).get('sha256')}`

---

## 4. Threat & Risk Assessment
**Threat Level:** `{result.get('threat_level')}`  
**Assessment:**  
{result.get('risk_summary')}

### Detected Deception Techniques
"""
    anomalies = result.get("anomalies", [])
    if anomalies:
        for a in anomalies:
            md += f"- **{a.get('type')}** [{a.get('severity')}]: {a.get('detail')}\n"
    else:
        md += "- No obfuscation or naming anomalies detected.\n"

    md += f"""
---

## 5. Security Disclaimer
> ⚠️ **Important:** {result.get('disclaimer')}
"""
    return md


def generate_json_report(result: Dict[str, Any]) -> str:
    """Generates a structured JSON forensic export."""
    payload = {
        "system": "FileGuard - Suspicious File Type Detection System",
        "version": "2.0.0",
        "timestamp": datetime.now().isoformat(),
        "analysis": result
    }
    return json.dumps(payload, indent=2)
